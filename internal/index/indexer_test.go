func writeFile(t *testing.T, root, rel, content string) {
	t.Helper()
	p := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

// newProject creates a project with a .uxor.yaml marker.
func newProject(t *testing.T, files map[string]string) *config.Project {
	t.Helper()
	root, _ := filepath.EvalSymlinks(t.TempDir())
	writeFile(t, root, config.FileName, "")
	for rel, c := range files {
		writeFile(t, root, rel, c)
	}
	p, err := config.Open(root)
	if err != nil {
		t.Fatal(err)
	}
	return p
}

func openStore(t *testing.T, p *config.Project) *store.Store {
	t.Helper()
	st, err := store.Open(context.Background(), p.DBPath, store.Options{})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { st.Close() })
	return st
}

func run(t *testing.T, p *config.Project, st *store.Store, opt Options) *Result {
	t.Helper()
	res, err := Run(context.Background(), p, st, opt)
	if err != nil {
		t.Fatal(err)
	}
	return res
}

func paths(t *testing.T, st *store.Store) []string {
	t.Helper()
	ps, err := st.Paths(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	return ps
}

func TestIncremental(t *testing.T) {
	p := newProject(t, map[string]string{
		"a.go":       "package a\n\nfunc Alpha() {}\n",
		"b.go":       "package a\n\nfunc Beta() {}\n",
		"lib/c.py":   "def gamma():\n    pass\n",
		"web/d.ts":   "export function delta() {}\n",
		"README.md":  "# not code\n",
		"big/gen.go": "// Code generated by x. DO NOT EDIT.\npackage big\n",
	})
	st := openStore(t, p)
	ctx := context.Background()

	r := run(t, p, st, Options{})
	if r.Parsed != 4 || r.Skipped != 1 || r.Scanned != 5 {
		t.Fatalf("first run = %+v", r)
	}

	r = run(t, p, st, Options{})
	if r.Parsed != 0 || r.Unchanged != 4 {
		t.Fatalf("no-op run = %+v", r)
	}

	// Touch without content change: hashed but not re-parsed.
	future := time.Now().Add(time.Hour)
	os.Chtimes(filepath.Join(p.Root, "a.go"), future, future)
	// Real edit.
	writeFile(t, p.Root, "b.go", "package a\n\nfunc Beta() {}\n\nfunc BetaTwo() {}\n")
	r = run(t, p, st, Options{})
	if r.Parsed != 1 || r.Unchanged != 3 {
		t.Fatalf("after touch+edit = %+v", r)
	}
	syms, _ := st.SymbolsInFile(ctx, "b.go")
	if len(syms) != 3 || syms[2].Name != "BetaTwo" {
		t.Fatalf("b.go symbols = %+v", syms)
	}
	r = run(t, p, st, Options{})
	if r.Parsed != 0 {
		t.Fatalf("touched file re-parsed on next run: %+v", r)
	}

	// Deletion.
	os.Remove(filepath.Join(p.Root, "lib", "c.py"))
	r = run(t, p, st, Options{})
	if r.Removed != 1 {
		t.Fatalf("after delete = %+v", r)
	}
	if got := paths(t, st); !slices.Equal(got, []string{"a.go", "b.go", "web/d.ts"}) {
		t.Fatalf("paths = %v", got)
	}

	// Single-file mode (hook): only the given path is touched.
	writeFile(t, p.Root, "web/d.ts", "export function delta() {}\nexport function epsilon() {}\n")
	writeFile(t, p.Root, "a.go", "package a\n\nfunc AlphaChanged() {}\n")
	r = run(t, p, st, Options{Paths: []string{filepath.Join(p.Root, "web", "d.ts")}})
	if r.Parsed != 1 || r.Scanned != 1 {
		t.Fatalf("single-file run = %+v", r)
	}
	if syms, _ := st.SymbolsInFile(ctx, "a.go"); syms[1].Name != "Alpha" {
		t.Error("single-file run must not re-index other files")
	}

	// Full rebuild.
	r = run(t, p, st, Options{Full: true})
	if r.Parsed != 3 {
		t.Fatalf("full run = %+v", r)
	}
}

func TestWalkerExcludesAndGitignore(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not installed")
	}
	p := newProject(t, map[string]string{
		"src/app.ts":                "export const x = 1;\n",
		"src/app.min.js":            "var a=1;\n",
		"node_modules/dep/index.js": "module.exports = 1;\n",
		"dist/out.js":               "x();\n",
		"ignored/skip.go":           "package ignored\n",
		"custom/gen/z.go":           "package gen\n",
		"types/index.d.ts":          "export declare const x: number;\n",
		"keep.py":                   "x = 1\n",
		".gitignore":                "ignored/\n",
	})
	writeFile(t, p.Root, config.FileName, "exclude: [\"custom/gen/**\"]\n")
	p, _ = config.Open(p.Root)
	if out, err := exec.Command("git", "-C", p.Root, "init", "-q").CombinedOutput(); err != nil {
		t.Fatalf("git init: %v %s", err, out)
	}
	m := NewMatcher(p.Config, nil)
	listing, err := Walk(context.Background(), p, m)
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, e := range listing.Entries {
		got = append(got, e.Path)
	}
	slices.Sort(got)
	if want := []string{"keep.py", "src/app.ts"}; !slices.Equal(got, want) {
		t.Errorf("git walk = %v, want %v", got, want)
	}

	// Without git, defaults still apply (gitignore is git's job).
	os.RemoveAll(filepath.Join(p.Root, ".git"))
	listing, _ = Walk(context.Background(), p, m)
	got = got[:0]
	for _, e := range listing.Entries {
		got = append(got, e.Path)
	}
	slices.Sort(got)
	if want := []string{"ignored/skip.go", "keep.py", "src/app.ts"}; !slices.Equal(got, want) {
		t.Errorf("fs walk = %v, want %v", got, want)
	}
}

func TestIsolation(t *testing.T) {
	parent, _ := filepath.EvalSymlinks(t.TempDir())
	a := filepath.Join(parent, "a")
	b := filepath.Join(parent, "b")
	writeFile(t, a, config.FileName, "")
	writeFile(t, a, "main.go", "package main\n\nfunc main() {}\n")
	writeFile(t, a, "nested/"+config.FileName, "")
	writeFile(t, a, "nested/inner.go", "package nested\n")
	writeFile(t, a, "sub/.git/HEAD", "ref: refs/heads/main\n")
	writeFile(t, a, "sub/s.go", "package sub\n")
	writeFile(t, b, config.FileName, "")
	writeFile(t, b, "other.go", "package other\n")
	if err := os.Symlink(filepath.Join(b, "other.go"), filepath.Join(a, "link.go")); err != nil {
		t.Fatal(err)
	}

	pa, _ := config.Open(filepath.Join(a, "main.go"))
	if pa.Root != a {
		t.Fatalf("root = %s, want %s", pa.Root, a)
	}
	st := openStore(t, pa)
	run(t, pa, st, Options{})
	if got := paths(t, st); !slices.Equal(got, []string{"main.go"}) {
		t.Errorf("project a indexed %v; nested projects and out-of-root links must be skipped", got)
	}
	if _, err := os.Stat(filepath.Join(b, config.DataDirName)); !os.IsNotExist(err) {
		t.Error("indexing a wrote into project b")
	}

	// A hook passing a file from another project must not touch this index.
	r := run(t, pa, st, Options{Paths: []string{filepath.Join(b, "other.go"), "../b/other.go"}})
	if r.Parsed != 0 || r.Removed != 0 {
		t.Errorf("out-of-root paths were processed: %+v", r)
	}

	// include_nested opts back in for monorepos.
	writeFile(t, a, config.FileName, "include_nested: true\n")
	pa, _ = config.Open(a)
	run(t, pa, st, Options{})
	if got := paths(t, st); !slices.Contains(got, "nested/inner.go") {
		t.Errorf("include_nested: got %v", got)
	}
}

func TestForget(t *testing.T) {
	p := newProject(t, map[string]string{
		"app/main.go":        "package app\n",
		"secrets/keys.go":    "package secrets\n",
		"legacy/old/util.py": "def f(): pass\n",
	})
	st := openStore(t, p)
	ctx := context.Background()
	run(t, p, st, Options{})

	globs := []string{"secrets/**", "legacy"}
	if err := p.SetForgetGlobs(globs); err != nil {
		t.Fatal(err)
	}
	n, err := Forget(ctx, p, st, globs)
	if err != nil || n != 2 {
		t.Fatalf("Forget = %d, %v", n, err)
	}
	if got := paths(t, st); !slices.Equal(got, []string{"app/main.go"}) {
		t.Fatalf("after forget: %v", got)
	}
	// Forgotten paths stay out on re-index, even when edited.
	writeFile(t, p.Root, "secrets/keys.go", "package secrets\n\nvar K = 1\n")
	run(t, p, st, Options{})
	run(t, p, st, Options{Paths: []string{"secrets/keys.go"}})
	if got := paths(t, st); !slices.Equal(got, []string{"app/main.go"}) {
		t.Fatalf("forgotten paths came back: %v", got)
	}
	// unforget + index brings them back.
	if err := p.SetForgetGlobs([]string{"legacy"}); err != nil {
		t.Fatal(err)
	}
	run(t, p, st, Options{})
	if got := paths(t, st); !slices.Equal(got, []string{"app/main.go", "secrets/keys.go"}) {
		t.Fatalf("after unforget: %v", got)
	}
}

func TestProgress(t *testing.T) {
	p := newProject(t, map[string]string{
		"a.go": "package a\n\nfunc A() { B() }\n",
		"b.go": "package a\n\nfunc B() {}\n",
		"c.py": "def c():\n    pass\n",
	})
	st := openStore(t, p)
	var events []Event
	run(t, p, st, Options{Progress: func(ev Event) { events = append(events, ev) }})

	var stages []string
	parsed := 0
	for _, ev := range events {
		if len(stages) == 0 || stages[len(stages)-1] != ev.Stage {
			stages = append(stages, ev.Stage)
		}
		if ev.Stage == "parsing" {
			if ev.Total != 3 || ev.Done > ev.Total {
				t.Errorf("parsing event %+v", ev)
			}
			parsed = ev.Done
		}
	}
	if !slices.Equal(stages, []string{"scanning", "parsing", "resolving", "done"}) {
		t.Errorf("stages %v", stages)
	}
	if parsed != 3 {
		t.Errorf("last parsing event Done=%d, want 3", parsed)
	}

	// Nothing changed: parsing reports zero of zero, and nothing breaks.
	events = nil
	run(t, p, st, Options{Progress: func(ev Event) { events = append(events, ev) }})
	if len(events) == 0 || events[len(events)-1].Stage != "done" {
		t.Errorf("unchanged run events %+v", events)
	}
}

// TestParserVersionReparses: files indexed by older extraction rules are
// re-parsed by the next whole-project run, even though they look unchanged;
// path-scoped runs never do it (D34).
func TestParserVersionReparses(t *testing.T) {
	p := newProject(t, map[string]string{
		"a.go": "package a\n\nfunc A() {}\n",
		"b.go": "package a\n\nfunc B() {}\n",
	})
	st := openStore(t, p)
	ctx := context.Background()
	if res := run(t, p, st, Options{}); res.Parsed != 2 || res.Reparsed {
		t.Fatalf("first run: %+v", res)
	}
	if v, _ := st.Meta(ctx, "parser_version"); v != parse.Version {
		t.Fatalf("parser_version %q, want %q", v, parse.Version)
	}
	if res := run(t, p, st, Options{}); res.Parsed != 0 || res.Reparsed {
		t.Fatalf("unchanged run re-parsed: %+v", res)
	}

	if err := st.SetMeta(ctx, "parser_version", "old"); err != nil {
		t.Fatal(err)
	}
	if res := run(t, p, st, Options{Paths: []string{"a.go"}}); res.Reparsed {
		t.Error("a path-scoped run re-parsed everything")
	}
	if res := run(t, p, st, Options{}); res.Parsed != 2 || !res.Reparsed {
		t.Errorf("old rules: want every file re-parsed, got %+v", res)
	}
	if v, _ := st.Meta(ctx, "parser_version"); v != parse.Version {
		t.Errorf("parser_version %q after re-parse", v)
	}
	if got := paths(t, st); !slices.Equal(got, []string{"a.go", "b.go"}) {
		t.Errorf("files after re-parse: %v", got)
	}
}
