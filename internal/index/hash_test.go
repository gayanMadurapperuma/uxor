package index

import (
	"strings"
	"testing"
)

func TestIsGenerated(t *testing.T) {
	cases := []struct {
		src  string
		want bool
	}{
		{"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n", true},
		{"# @generated by tool\nx = 1\n", true},
		{"/**\n * @generated\n */\nexport const x = 1;\n", true},
		{"// mentions \"Code generated ... DO NOT EDIT\" in prose\npackage x\n", false},
		{"package x\n\nfunc f() {}\n", false},
		{strings.Repeat("a", 5000), true}, // minified: one huge line
	}
	for i, c := range cases {
		if got := isGenerated([]byte(c.src)); got != c.want {
			t.Errorf("case %d: got %v, want %v", i, got, c.want)
		}
	}
}
